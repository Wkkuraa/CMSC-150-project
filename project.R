build_matrix <- function(primal, selected, CO2_ON, CO2_limit){
  currmatrix <- primal
  plantgroups <- c("Coal", "Nat.Gas", "Geo", "Hydro", "Oil", "Solar", "Wind")
  toremove <- setdiff(plantgroups,selected) #contains the elements in plant groups that are not in selected
  #setdiff function was based on here: https://www.geeksforgeeks.org/r-language/get-exclusive-elements-between-two-objects-in-r-programming-setdiff-function/
  delete_rows<-logical(nrow(currmatrix)) #creates a vector containing false the amount of the number of rows in the matrix
  delete_cols<-logical(ncol(currmatrix)) #the same but with the number of columns in the matrix
  
  #background on startswith:https://www.rdocumentation.org/packages/base/versions/3.6.2/topics/startsWith
  #logic was based on
  for (name in toremove){ #loops through the values in to find the rows and columns to remove
    delete_rows<- delete_rows | startsWith(rownames(currmatrix),name) #startswith checks if the row matches with any name in the toremove vector
    #if it does match any of the name in the matrix we flip it to TRUE if we want to delete it
    delete_cols<- delete_cols | startsWith(colnames(currmatrix),name) #same logic just ccolumns this time
  }
  #logic of removing was based on the google search: how to remove selected rows in matrix in R using column or row names
  currmatrix<-currmatrix[delete_rows==FALSE,delete_cols==FALSE, drop =FALSE]
  
  if(CO2_ON==FALSE){ #just checks if cO2 is false if it is false we remove the CO2 cap
    currmatrix <- currmatrix[rownames(currmatrix) != "CO2Cap", , drop=FALSE]
  } else {
    currmatrix["CO2Cap", ncol(currmatrix)] <- CO2_limit #else we find the row  that has the name co2 cap and append it
  }
  
  #this is where we transpose the matrix and then we insert the slack variables
  slack_variables <- ncol(currmatrix)-1 #finds where we insert the slack variables it is usually before the last column
  slack <- rbind(diag(slack_variables),0) #Initializes a diagonal matrix the size of the columns of the currmatrix minus 1 and appending a a row of 0s to account for the CO2 rows that has only 0 on it
  init_tableau <- t(currmatrix) #transposes the matrix
  dimnames(init_tableau) <- NULL #removes the names of the function for printing purposes can be removed so we can see it clearly and also because we don't want the names to be mismatched
  #the code below is the append logic we basically use cbind to append the matrix to the column before the last column in the current matrix 
  init_tableau<- cbind(init_tableau[ , 1:(ncol(init_tableau) - 1), drop=FALSE],slack,init_tableau[,ncol(init_tableau), drop=FALSE])
  #the values of init tableau are just where we want the slack variables to be inserted in
  lastrow<-nrow(init_tableau) #The 2 lines are just placeholders for the last row and column after appending
  lastcol <- ncol(init_tableau)
  init_tableau[lastrow, 1:(lastcol - 1)] <- -init_tableau[lastrow, 1:(lastcol - 1)] #flips the sign of the last row to keep the positivity constraint
  return(init_tableau)
  }


